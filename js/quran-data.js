export function calculateAverageRating(records) {
  if (!records || records.length === 0) return { label: "N/A", points: 0, badgeClass: "badge-neutral" };
  const totalPoints = records.reduce((sum, r) => {
    const ratingObj = PERFORMANCE_RATINGS.find(p => p.value === r.rating);
    return sum + (ratingObj ? ratingObj.points : 2);
  }, 0);
  const avg = totalPoints / records.length;
  if (avg >= 3.5) return { label: "Excellent", points: avg.toFixed(1), badgeClass: "badge-excellent", color: "#10b981" };
  if (avg >= 2.5) return { label: "Good", points: avg.toFixed(1), badgeClass: "badge-good", color: "#3b82f6" };
  if (avg >= 1.5) return { label: "Fair", points: avg.toFixed(1), badgeClass: "badge-fair", color: "#f59e0b" };
  return { label: "Needs Practice", points: avg.toFixed(1), badgeClass: "badge-poor", color: "#ef4444" };
}
